static MsValue unicode_rune_count(MsVM* vm, int argc, MsValue* argv) {
    (void)argc;
    if (!MS_IS_STRING(argv[0])) {
        ms_vm_runtime_error(vm, "unicode.rune_count: expected str");
        return MS_NIL_VAL();
    }
    MsObjString* s = MS_AS_STRING(argv[0]);
    const uint8_t* p = (const uint8_t*)s->data;
    size_t left = (size_t)s->length;
    ms_i64 count = 0;
    while (left > 0) {
        uint32_t cp;
        int n = utf8_decode_one(p, left, &cp);
        if (n <= 0) { p++; left--; count++; } /* invalid byte: count as 1 */
        else { p += n; left -= (size_t)n; count++; }
    }
    return MS_INT_VAL(count);
}

static MsValue unicode_rune_at(MsVM* vm, int argc, MsValue* argv) {
    (void)argc;
    if (!MS_IS_STRING(argv[0])) {
        ms_vm_runtime_error(vm, "unicode.rune_at: expected str");
        return MS_NIL_VAL();
    }
    if (!MS_IS_INT(argv[1])) {
        ms_vm_runtime_error(vm, "unicode.rune_at: index must be int");
        return MS_NIL_VAL();
    }
    MsObjString* s = MS_AS_STRING(argv[0]);
    ms_i64 target = MS_AS_INT(argv[1]);
    const uint8_t* p = (const uint8_t*)s->data;
    size_t left = (size_t)s->length;
    ms_i64 idx = 0;
    while (left > 0) {
        uint32_t cp;
        int n = utf8_decode_one(p, left, &cp);
        if (n <= 0) { n = 1; cp = (uint32_t)*p; }
        if (idx == target) return cp_to_str(vm, cp);
        p += n; left -= (size_t)n; idx++;
    }
    ms_vm_runtime_error(vm, "unicode.rune_at: index %lld out of bounds", (long long)target);
    return MS_NIL_VAL();
}

static MsValue unicode_runes(MsVM* vm, int argc, MsValue* argv) {
    (void)argc;
    if (!MS_IS_STRING(argv[0])) {
        ms_vm_runtime_error(vm, "unicode.runes: expected str");
        return MS_NIL_VAL();
    }
    MsObjString* s = MS_AS_STRING(argv[0]);
    const uint8_t* p = (const uint8_t*)s->data;
    size_t left = (size_t)s->length;
    MsObjList* lst = ms_obj_list_new(vm);
    while (left > 0) {
        uint32_t cp;
        int n = utf8_decode_one(p, left, &cp);
        if (n <= 0) { n = 1; cp = (uint32_t)*p; }
        MsValue sv = cp_to_str(vm, cp);
        ms_value_array_push(&lst->items, sv);
        p += n; left -= (size_t)n;
    }
    return MS_OBJ_VAL(lst);
}

static MsValue unicode_encode_utf8(MsVM* vm, int argc, MsValue* argv) {
    (void)argc;
    uint32_t cp;
    if (!coerce_codepoint(vm, argv[0], &cp, "unicode.encode_utf8")) return MS_NIL_VAL();
    uint8_t buf[4];
    int n = utf8_encode_one(cp, buf);
    return MS_OBJ_VAL(ms_obj_buffer_from_bytes(vm, buf, (size_t)n));
}

static MsValue unicode_decode_utf8(MsVM* vm, int argc, MsValue* argv) {
    /* decode_utf8(buf_or_str, offset=0) → [str, nbytes] */
    const uint8_t* data;
    size_t data_len;

    if (MS_IS_BUFFER(argv[0])) {
        MsObjBuffer* b = MS_AS_BUFFER(argv[0]);
        data = b->data; data_len = b->len;
    } else if (MS_IS_STRING(argv[0])) {
        MsObjString* s = MS_AS_STRING(argv[0]);
        data = (const uint8_t*)s->data; data_len = (size_t)s->length;
    } else {
        ms_vm_runtime_error(vm, "unicode.decode_utf8: expected str or buffer");
        return MS_NIL_VAL();
    }

    ms_i64 off = (argc >= 2 && MS_IS_INT(argv[1])) ? MS_AS_INT(argv[1]) : 0;
    if (off < 0 || (size_t)off >= data_len) {
        ms_vm_runtime_error(vm, "unicode.decode_utf8: offset %lld out of range",
                            (long long)off);
        return MS_NIL_VAL();
    }

    uint32_t cp;
    int n = utf8_decode_one(data + off, data_len - (size_t)off, &cp);
    if (n <= 0) {
        ms_vm_runtime_error(vm, "unicode.decode_utf8: invalid UTF-8 at offset %lld",
                            (long long)off);
        return MS_NIL_VAL();
    }

    MsObjList* result = ms_obj_list_new(vm);
    ms_value_array_push(&result->items, cp_to_str(vm, cp));
    ms_value_array_push(&result->items, MS_INT_VAL((ms_i64)n));
    return MS_OBJ_VAL(result);
}

static MsValue unicode_valid_utf8(MsVM* vm, int argc, MsValue* argv) {
    (void)argc;
    const uint8_t* data;
    size_t data_len;
    if (MS_IS_STRING(argv[0])) {
        MsObjString* s = MS_AS_STRING(argv[0]);
        data = (const uint8_t*)s->data; data_len = (size_t)s->length;
    } else if (MS_IS_BUFFER(argv[0])) {
        MsObjBuffer* b = MS_AS_BUFFER(argv[0]);
        data = b->data; data_len = b->len;
    } else {
        ms_vm_runtime_error(vm, "unicode.valid_utf8: expected str or buffer");
        return MS_NIL_VAL();
    }
    const uint8_t* p = data;
    size_t left = data_len;
    while (left > 0) {
        uint32_t cp;
        int n = utf8_decode_one(p, left, &cp);
        if (n <= 0) return MS_BOOL_VAL(false);
        p += n; left -= (size_t)n;
    }
    return MS_BOOL_VAL(true);
}

