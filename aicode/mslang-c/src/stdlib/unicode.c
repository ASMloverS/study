static MsValue unicode_ord(MsVM* vm, int argc, MsValue* argv) {
    (void)argc;
    if (!MS_IS_STRING(argv[0])) {
        ms_vm_runtime_error(vm, "unicode.ord: expected str");
        return MS_NIL_VAL();
    }
    MsObjString* s = MS_AS_STRING(argv[0]);
    if (s->length == 0) {
        ms_vm_runtime_error(vm, "unicode.ord: empty string");
        return MS_NIL_VAL();
    }
    uint32_t cp;
    int n = utf8_decode_one((const uint8_t*)s->data, (size_t)s->length, &cp);
    if (n <= 0) {
        ms_vm_runtime_error(vm, "unicode.ord: invalid UTF-8");
        return MS_NIL_VAL();
    }
    return MS_INT_VAL((ms_i64)cp);
}

static MsValue unicode_chr(MsVM* vm, int argc, MsValue* argv) {
    (void)argc;
    if (!MS_IS_INT(argv[0])) {
        ms_vm_runtime_error(vm, "unicode.chr: expected int");
        return MS_NIL_VAL();
    }
    ms_i64 n = MS_AS_INT(argv[0]);
    if (n < 0 || n > 0x10FFFF) {
        ms_vm_runtime_error(vm, "unicode.chr: code point %lld out of range",
                            (long long)n);
        return MS_NIL_VAL();
    }
    return cp_to_str(vm, (uint32_t)n);
}

