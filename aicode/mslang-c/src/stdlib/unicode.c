/* Range lookup                                                         */
/* ------------------------------------------------------------------ */

static bool in_ranges16(const URange16* ranges, int count, uint32_t cp) {
    if (cp > 0xFFFF) return false;
    uint16_t c = (uint16_t)cp;
    int lo = 0, hi = count - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (c < ranges[mid].lo)      hi = mid - 1;
        else if (c > ranges[mid].hi) lo = mid + 1;
        else                         return true;
    }
    return false;
}

static bool cp_is_letter(uint32_t cp) {
    if (cp > 0x10FFFF) return false;
    if (cp > 0xFFFF) return true; /* supplementary planes mostly letters */
    return in_ranges16(kLetterRanges, kLetterCount, cp);
}

static bool cp_is_digit(uint32_t cp) {
    return in_ranges16(kDigitRanges, kDigitCount, cp);
}

static bool cp_is_space(uint32_t cp) {
    for (int i = 0; i < kSpaceCount; i++)
        if (kSpacePoints[i] == cp) return true;
    return false;
}

static bool cp_is_upper(uint32_t cp) {
    return in_ranges16(kUpperRanges, kUpperCount, cp);
}

static bool cp_is_lower(uint32_t cp) {
    return in_ranges16(kLowerRanges, kLowerCount, cp);
}

static bool cp_is_punct(uint32_t cp) {
    return in_ranges16(kPunctRanges, kPunctCount, cp);
}

static bool cp_is_graphic(uint32_t cp) {
    /* Graphic = has visible form; exclude control chars, surrogates, nonchars */
    if (cp < 0x20) return false;
    if (cp == 0x7F) return false;
    if (cp >= 0x80 && cp < 0xA0) return false;
    if (cp >= 0xD800 && cp <= 0xDFFF) return false;
    if ((cp & 0xFFFF) == 0xFFFE || (cp & 0xFFFF) == 0xFFFF) return false;
    if (cp_is_space(cp) && cp != 0x0020) return false;
    return cp <= 0x10FFFF;
}

/* ------------------------------------------------------------------ */
/* Helper: make a single-char string from code point                   */
/* ------------------------------------------------------------------ */
static MsValue cp_to_str(MsVM* vm, uint32_t cp) {
    uint8_t buf[4];
    int n = utf8_encode_one(cp, buf);
    return MS_OBJ_VAL(ms_obj_string_copy(vm, (const char*)buf, n));
}

