/* Decode one UTF-8 sequence starting at p (with remaining bytes left).
 * Sets *out_cp to the code point and returns byte length (1–4), or 0
 * on invalid sequence. */
static int utf8_decode_one(const uint8_t* p, size_t left, uint32_t* out_cp) {
    if (left == 0) return 0;
    uint8_t b0 = p[0];
    if (b0 < 0x80) {
        *out_cp = b0;
        return 1;
    }
    if ((b0 & 0xE0) == 0xC0) {
        if (left < 2 || (p[1] & 0xC0) != 0x80) return 0;
        uint32_t cp = ((uint32_t)(b0 & 0x1F) << 6) | (p[1] & 0x3F);
        if (cp < 0x80) return 0; /* overlong */
        *out_cp = cp;
        return 2;
    }
    if ((b0 & 0xF0) == 0xE0) {
        if (left < 3 || (p[1] & 0xC0) != 0x80 || (p[2] & 0xC0) != 0x80) return 0;
        uint32_t cp = ((uint32_t)(b0 & 0x0F) << 12)
                    | ((uint32_t)(p[1] & 0x3F) << 6)
                    |  (p[2] & 0x3F);
        if (cp < 0x800) return 0;
        if (cp >= 0xD800 && cp <= 0xDFFF) return 0; /* surrogates */
        *out_cp = cp;
        return 3;
    }
    if ((b0 & 0xF8) == 0xF0) {
        if (left < 4 || (p[1] & 0xC0) != 0x80
                     || (p[2] & 0xC0) != 0x80
                     || (p[3] & 0xC0) != 0x80) return 0;
        uint32_t cp = ((uint32_t)(b0 & 0x07) << 18)
                    | ((uint32_t)(p[1] & 0x3F) << 12)
                    | ((uint32_t)(p[2] & 0x3F) << 6)
                    |  (p[3] & 0x3F);
        if (cp < 0x10000 || cp > 0x10FFFF) return 0;
        *out_cp = cp;
        return 4;
    }
    return 0;
}

/* Encode code point cp into buf (must have ≥4 bytes). Returns byte count. */
static int utf8_encode_one(uint32_t cp, uint8_t* buf) {
    if (cp < 0x80) {
        buf[0] = (uint8_t)cp;
        return 1;
    }
    if (cp < 0x800) {
        buf[0] = (uint8_t)(0xC0 | (cp >> 6));
        buf[1] = (uint8_t)(0x80 | (cp & 0x3F));
        return 2;
    }
    if (cp < 0x10000) {
        buf[0] = (uint8_t)(0xE0 | (cp >> 12));
        buf[1] = (uint8_t)(0x80 | ((cp >> 6) & 0x3F));
        buf[2] = (uint8_t)(0x80 | (cp & 0x3F));
        return 3;
    }
    buf[0] = (uint8_t)(0xF0 | (cp >> 18));
    buf[1] = (uint8_t)(0x80 | ((cp >> 12) & 0x3F));
    buf[2] = (uint8_t)(0x80 | ((cp >> 6)  & 0x3F));
    buf[3] = (uint8_t)(0x80 | (cp & 0x3F));
    return 4;
}

/* ------------------------------------------------------------------ */
/* Coerce MsValue (int code point OR single-char string) → uint32_t   */
/* Returns false and sets runtime error on invalid input.              */
/* ------------------------------------------------------------------ */
static bool coerce_codepoint(MsVM* vm, MsValue v, uint32_t* out_cp,
                              const char* fn_name) {
    if (MS_IS_INT(v)) {
        ms_i64 n = MS_AS_INT(v);
        if (n < 0 || n > 0x10FFFF) {
            ms_vm_runtime_error(vm, "%s: code point %lld out of range", fn_name,
                                (long long)n);
            return false;
        }
        *out_cp = (uint32_t)n;
        return true;
    }
    if (MS_IS_STRING(v)) {
        MsObjString* s = MS_AS_STRING(v);
        if (s->length == 0) {
            ms_vm_runtime_error(vm, "%s: empty string", fn_name);
            return false;
        }
        uint32_t cp = 0;
        int n = utf8_decode_one((const uint8_t*)s->data, (size_t)s->length, &cp);
        if (n <= 0) {
            ms_vm_runtime_error(vm, "%s: invalid UTF-8", fn_name);
            return false;
        }
        *out_cp = cp;
        return true;
    }
    ms_vm_runtime_error(vm, "%s: expected int or str", fn_name);
    return false;
}

