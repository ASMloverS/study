/* Simple case-fold table (only ASCII + Latin Extended covers most needs).
 * A complete BMP table would be ~32KB.  We cover U+0041–U+00FF. */

/* to_upper for the range 0x00–0xFF */
static uint32_t simple_to_upper(uint32_t cp) {
    /* ASCII lower → upper */
    if (cp >= 0x0061 && cp <= 0x007A) return cp - 0x20;
    /* Latin-1 lower → upper (select) */
    if (cp >= 0x00E0 && cp <= 0x00F6) return cp - 0x20;
    if (cp >= 0x00F8 && cp <= 0x00FE) return cp - 0x20;
    /* Latin Extended-A: even=upper, odd=lower for pairs 0x0100–0x012E, etc. */
    if (cp >= 0x0100 && cp <= 0x012E && (cp & 1) == 1) return cp - 1;
    if (cp >= 0x0130 && cp <= 0x0136 && (cp & 1) == 1) return cp - 1;
    if (cp >= 0x0139 && cp <= 0x0148 && (cp & 1) == 0) return cp - 1;
    if (cp >= 0x014A && cp <= 0x0177 && (cp & 1) == 1) return cp - 1;
    if (cp == 0x017A || cp == 0x017C || cp == 0x017E) return cp - 1;
    /* Greek lower (0x03B1–0x03C9) → upper (0x0391–0x03A9) */
    if (cp >= 0x03B1 && cp <= 0x03C9) return cp - 0x20;
    if (cp >= 0x03AC && cp <= 0x03AE) {
        static const uint32_t map[] = {0x0386,0x0388,0x0389,0x038A};
        return map[cp - 0x03AC];
    }
    /* Cyrillic 0x0430–0x044F → 0x0410–0x042F */
    if (cp >= 0x0430 && cp <= 0x044F) return cp - 0x20;
    return cp; /* unchanged */
}

static uint32_t simple_to_lower(uint32_t cp) {
    /* ASCII upper → lower */
    if (cp >= 0x0041 && cp <= 0x005A) return cp + 0x20;
    /* Latin-1 upper → lower */
    if (cp >= 0x00C0 && cp <= 0x00D6) return cp + 0x20;
    if (cp >= 0x00D8 && cp <= 0x00DE) return cp + 0x20;
    /* Latin Extended-A pairs */
    if (cp >= 0x0100 && cp <= 0x012E && (cp & 1) == 0) return cp + 1;
    if (cp >= 0x0130 && cp <= 0x0136 && (cp & 1) == 0) return cp + 1;
    if (cp >= 0x0139 && cp <= 0x0148 && (cp & 1) == 1) return cp + 1;
    if (cp >= 0x014A && cp <= 0x0177 && (cp & 1) == 0) return cp + 1;
    if (cp == 0x0179 || cp == 0x017B || cp == 0x017D) return cp + 1;
    /* Greek upper (0x0391–0x03A9) → lower */
    if (cp >= 0x0391 && cp <= 0x03A9) return cp + 0x20;
    if (cp == 0x0386) return 0x03AC;
    if (cp == 0x0388) return 0x03AD;
    if (cp == 0x0389) return 0x03AE;
    if (cp == 0x038A) return 0x03AF;
    /* Cyrillic 0x0410–0x042F → 0x0430–0x044F */
    if (cp >= 0x0410 && cp <= 0x042F) return cp + 0x20;
    return cp;
}

